import { lazy, Suspense, useEffect, useRef, useState } from 'react';
import { useLang } from '../../i18n';
import audio1 from '../../content/misty-lesson1-audio.json';
import audio2 from '../../content/misty-lesson2-audio.json';
import './misty.css';

const MistyTranscript = lazy(() => import('./MistyTranscript'));
const BASE = import.meta.env.BASE_URL;
const AUDIO = { 1: audio1, 2: audio2 } as const;

const TEXT = {
  1: {
    title: ['A Misty explica o perceptron', 'Misty explains the perceptron'],
    about: [
      'A líder do Ginásio de Celeste refaz a Aula 1 com você, conta por conta, com analogias de batalha.',
      'The Cerulean City Gym Leader goes through Lesson 1 with you, one calculation at a time, with battle analogies.',
    ],
  },
  2: {
    title: ['A Misty explica o MLP', 'Misty explains the MLP'],
    about: [
      'A líder do Ginásio de Celeste refaz a Aula 2 com você: por que o Venusaur escapava, a camada oculta e o backpropagation, conta por conta.',
      'The Cerulean City Gym Leader goes through Lesson 2 with you: why Venusaur kept breaking free, the hidden layer and backpropagation, one calculation at a time.',
    ],
  },
} as const;

function clock(s: number): string {
  const t = Math.max(0, Math.floor(s));
  return `${Math.floor(t / 60)}:${String(t % 60).padStart(2, '0')}`;
}

/**
 * Small item under each lesson: Misty, as a fellow trainer, goes through the lesson in a ~13 min audio.
 * Voice: Qwen3-TTS CustomVoice, speaker "vivian" (Apache 2.0), a stock voice, not Misty's voice actress.
 * Generated by scripts/misty_tts.py, which checks every number of the audio with Whisper.
 */
export default function MistyAudio({ lesson = 1 }: { lesson?: 1 | 2 }) {
  const { lang } = useLang();
  const pt = lang === 'pt';
  const i = pt ? 0 : 1;
  const meta = AUDIO[lesson][lang];
  const id = lesson === 1 ? 'misty' : `misty-${lesson}`;
  const audio = useRef<HTMLAudioElement>(null);
  const [open, setOpen] = useState(false);
  const [playing, setPlaying] = useState(false);
  const [time, setTime] = useState(0);

  // The language switch changes the file: stop and go back to the start.
  useEffect(() => {
    setPlaying(false);
    setTime(0);
  }, [lang]);

  const section = meta.starts.reduce((cur, s, i) => (time >= s ? i : cur), 0);

  function toggle() {
    const a = audio.current;
    if (!a) return;
    setOpen(true);
    if (a.paused) void a.play();
    else a.pause();
  }

  function seek(i: number) {
    const a = audio.current;
    if (!a) return;
    a.currentTime = meta.starts[i];
    setTime(meta.starts[i]);
    void a.play();
  }

  return (
    <section className="lesson misty-branch" id={id} aria-labelledby={`${id}-title`}>
      <div className={`panel misty-card ${playing ? 'playing' : ''}`}>
        <button className="misty-face" onClick={toggle} aria-label={playing ? (pt ? 'Pausar o áudio' : 'Pause the audio') : (pt ? 'Ouvir a Misty' : 'Listen to Misty')}>
          <img src={`${BASE}misty.jpg`} alt="" width={48} height={48} />
          <span className="misty-play" aria-hidden="true">{playing ? '❚❚' : '▶'}</span>
        </button>
        <div className="misty-text">
          <span className="label">{pt ? 'Áudio · Aula' : 'Audio · Lesson'} {lesson} · {clock(meta.duration)}</span>
          <h3 id={`${id}-title`}>{TEXT[lesson].title[i]}</h3>
          <p>{TEXT[lesson].about[i]}</p>
        </div>
        <button className="btn btn--ghost btn--sm" onClick={() => setOpen((o) => !o)} aria-expanded={open} aria-controls={`${id}-body`}>
          {open ? (pt ? '▴ Fechar' : '▴ Close') : (pt ? '▾ Capítulos e texto' : '▾ Chapters and text')}
        </button>
      </div>

      <audio
        ref={audio}
        key={lang}
        src={`${BASE}audio/misty_lesson${lesson}_${lang}.mp3`}
        preload="none"
        controls={open}
        className="misty-audio"
        hidden={!open}
        onPlay={() => setPlaying(true)}
        onPause={() => setPlaying(false)}
        onEnded={() => setPlaying(false)}
        onTimeUpdate={(e) => setTime(e.currentTarget.currentTime)}
      />

      {open && (
        <div id={`${id}-body`} className="misty-body">
          <Suspense fallback={<p className="small muted">{pt ? 'Carregando o texto…' : 'Loading the text…'}</p>}>
            <MistyTranscript lesson={lesson} current={playing || time > 0 ? section : -1} starts={meta.starts} onSeek={seek} />
          </Suspense>
          <p className="small muted misty-credit">
            {pt
              ? 'Voz sintética (Qwen3-TTS, voz Vivian, licença Apache 2.0), escolhida por lembrar o tom da Misty; não é a voz da dubladora. O áudio lê o mesmo texto mostrado acima, e cada número dele foi conferido por transcrição automática.'
              : 'Synthetic voice (Qwen3-TTS, voice Vivian, Apache 2.0 license), picked because it sounds close to Misty\'s tone; it is not the voice actress. The audio reads the same text shown above, and every number in it was checked by automatic transcription.'}
          </p>
        </div>
      )}
    </section>
  );
}
